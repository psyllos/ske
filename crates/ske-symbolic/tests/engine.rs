fn ins(
    id: &str,
    block: &str,
    opcode: &str,
    args: &[&str],
    result: &str,
    term: bool,
) -> InstructionDef {
    InstructionDef {
        id: id.into(),
        block_id: block.into(),
        opcode: opcode.into(),
        operand_value_ids: args.iter().map(|s| s.to_string()).collect(),
        result_value_id: result.into(),
        is_terminator: term,
        ..Default::default()
    }
}
fn edge(id: &str, source: &str, target: &str, ordinal: u32) -> Edge {
    Edge {
        definition: ControlEdgeDef {
            id: id.into(),
            source_block_id: source.into(),
            target_block_id: target.into(),
            outcome_ordinal: ordinal,
            edge_kind: if ordinal == 0 {
                "BRANCH_TRUE"
            } else {
                "BRANCH_FALSE"
            }
            .into(),
            ..Default::default()
        },
        outcome_id: Some(id.into()),
    }
}
// A small hand-written Decide-shaped CFG, not output generated by the engine.
fn enum_literal(bytes: &[u8]) -> LiteralValue {
    LiteralValue {
        representation: Some(literal_value::Representation::StringBytes(bytes.to_vec())),
    }
}
fn enum_machine(bits: u128, width: u32) -> LiteralValue {
    LiteralValue {
        representation: Some(literal_value::Representation::MachineBitsBe(
            bits.to_be_bytes()[16 - (width as usize).div_ceil(8)..].to_vec(),
        )),
    }
}

// A StringBytes CONST is not functionally encoded (§4.4/§6.4): its HAVOC makes
// the state OPAQUE, never silently EXACT (AC prop_unsupported_never_exact).
#[test]
fn string_constant_degrades_to_opaque_and_emits_diagnostic() {
    let mut program = decide();
    program.types.insert(
        "str".into(),
        TypeDef {
            id: "str".into(),
            kind: "STRING".into(),
            ..Default::default()
        },
    );
    program.values.insert(
        "s".into(),
        ValueDef {
            id: "s".into(),
            role: "CONST".into(),
            type_id: "str".into(),
            literal: Some(enum_literal(b"hello")),
            ..Default::default()
        },
    );
    let mut diagnostics = vec![];
    let report = analyze(
        &program,
        &Budget::default(),
        &mut ScriptedSolver::new(vec![sat(), sat()]),
        |_, _| Ok(vec![]),
        &|| false,
        &mut |event| {
            if let Event::Diagnostic(code) = event {
                diagnostics.push(code.clone());
            }
        },
    )
    .unwrap();
    assert!(diagnostics.contains(&"OPAQUE_OP_EMITTED".into()));
    assert!(!report.arrivals.is_empty());
    assert!(report
        .arrivals
        .iter()
        .all(|a| a.soundness >= Soundness::Opaque));
}

