#[test]
fn div_implicit_forks_obey_query_and_state_budgets() {
    let mut p = decide();
    p.types.insert(
        "i8".into(),
        TypeDef {
            id: "i8".into(),
            kind: "BITVECTOR".into(),
            bit_width: 8,
            is_signed: true,
            ..Default::default()
        },
    );
    for id in ["a", "b", "q"] {
        p.values.insert(
            id.into(),
            ValueDef {
                id: id.into(),
                type_id: "i8".into(),
                role: if id == "q" { "SSA" } else { "PARAM" }.into(),
                param_index: if id == "a" {
                    Some(1)
                } else if id == "b" {
                    Some(2)
                } else {
                    None
                },
                ..Default::default()
            },
        );
    }
    p.blocks
        .get_mut("b0")
        .unwrap()
        .instructions
        .insert(0, ins("div", "b0", "DIV", &["a", "b"], "q", false));
    let r = analyze(
        &p,
        &Budget {
            max_solver_queries: 1,
            ..Default::default()
        },
        &mut ScriptedSolver::new(vec![sat()]),
        |_, _| Ok(vec![]),
        &|| false,
        &mut |_| {},
    )
    .unwrap();
    assert_eq!(r.queries.len(), 1);
    assert!(r
        .exits
        .iter()
        .any(|e| e.kind == "PANIC" && e.instruction_id == "div"));
    assert!(r
        .exits
        .iter()
        .filter(|e| e.kind == "PANIC")
        .all(|e| e.taken_outcomes.ordered().is_empty()));
    assert!(!r.exploration_closed);
    assert!(r.states_created >= 3);
}

