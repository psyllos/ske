fn decide() -> Program {
    let bool_type = TypeDef {
        id: "bool".into(),
        kind: "BOOL".into(),
        ..Default::default()
    };
    let x = ValueDef {
        id: "x".into(),
        role: "PARAM".into(),
        type_id: "bool".into(),
        param_index: Some(0),
        ..Default::default()
    };
    let b0 = Block {
        ordinal: 0,
        instructions: vec![ins("br0", "b0", "BRANCH", &["x"], "", true)],
        edges: vec![edge("o0", "b0", "ret", 0), edge("o1", "b0", "b1", 1)],
    };
    let b1 = Block {
        ordinal: 1,
        instructions: vec![ins("br1", "b1", "BRANCH", &["x"], "", true)],
        edges: vec![edge("o2", "b1", "ret", 0), edge("o3", "b1", "ret", 1)],
    };
    let ret = Block {
        ordinal: 2,
        instructions: vec![ins("ret", "ret", "RETURN", &[], "", true)],
        edges: vec![],
    };
    Program {
        function: FunctionDef {
            id: "f".into(),
            entry_block_id: "b0".into(),
            parameter_value_ids: vec!["x".into()],
            ..Default::default()
        },
        types: BTreeMap::from([("bool".into(), bool_type)]),
        values: BTreeMap::from([("x".into(), x)]),
        blocks: BTreeMap::from([("b0".into(), b0), ("b1".into(), b1), ("ret".into(), ret)]),
        symbols: BTreeMap::new(),
    }
}
fn run(results: Vec<CheckResult>, budget: Budget) -> Report {
    analyze(
        &decide(),
        &budget,
        &mut ScriptedSolver::new(results),
        |_, _| Ok(vec![]),
        &|| false,
        &mut |_| {},
    )
    .unwrap()
}
fn sat() -> CheckResult {
    CheckResult::Sat { model: None }
}

