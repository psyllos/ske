fn count3() -> Program {
    let mut p = decide();
    p.types.insert(
        "i8".into(),
        TypeDef {
            id: "i8".into(),
            kind: "BITVECTOR".into(),
            bit_width: 8,
            is_signed: true,
            ..Default::default()
        },
    );
    p.values.clear();
    for (id, bits) in [("zero", 0u8), ("one", 1), ("three", 3)] {
        p.values.insert(
            id.into(),
            ValueDef {
                id: id.into(),
                type_id: "i8".into(),
                role: "CONST".into(),
                literal: Some(LiteralValue {
                    representation: Some(literal_value::Representation::MachineBitsBe(vec![bits])),
                }),
                ..Default::default()
            },
        );
    }
    for (id, ty) in [("i", "i8"), ("next", "i8"), ("condition", "bool")] {
        p.values.insert(
            id.into(),
            ValueDef {
                id: id.into(),
                type_id: ty.into(),
                role: "SSA".into(),
                ..Default::default()
            },
        );
    }
    let mut phi = ins("phi", "header", "PHI", &[], "i", false);
    phi.payload = Some(OperationPayload {
        phi_inputs: vec![
            PhiInput {
                predecessor_block_id: "entry".into(),
                value_id: "zero".into(),
            },
            PhiInput {
                predecessor_block_id: "body".into(),
                value_id: "next".into(),
            },
        ],
        ..Default::default()
    });
    let mut add = ins("add", "body", "ADD", &["i", "one"], "next", false);
    add.payload = Some(OperationPayload {
        details: Some(operation_payload::Details::Binary(BinarySemantics {
            overflow_mode: "WRAP".into(),
            ..Default::default()
        })),
        ..Default::default()
    });
    let jump = |id: &str, source: &str, target: &str| Edge {
        definition: ControlEdgeDef {
            id: id.into(),
            source_block_id: source.into(),
            target_block_id: target.into(),
            edge_kind: "UNCONDITIONAL".into(),
            ..Default::default()
        },
        outcome_id: None,
    };
    p.blocks = BTreeMap::from([
        (
            "entry".into(),
            Block {
                ordinal: 0,
                instructions: vec![ins("j0", "entry", "JUMP", &[], "", true)],
                edges: vec![jump("j0", "entry", "header")],
            },
        ),
        (
            "header".into(),
            Block {
                ordinal: 1,
                instructions: vec![
                    phi,
                    ins("lt", "header", "LT", &["i", "three"], "condition", false),
                    ins("br", "header", "BRANCH", &["condition"], "", true),
                ],
                edges: vec![
                    edge("enter", "header", "body", 0),
                    edge("exit", "header", "ret", 1),
                ],
            },
        ),
        (
            "body".into(),
            Block {
                ordinal: 2,
                instructions: vec![add, ins("j1", "body", "JUMP", &[], "", true)],
                edges: vec![jump("j1", "body", "header")],
            },
        ),
        (
            "ret".into(),
            Block {
                ordinal: 3,
                instructions: vec![ins("ret", "ret", "RETURN", &[], "", true)],
                edges: vec![],
            },
        ),
    ]);
    p.function.entry_block_id = "entry".into();
    p.function.parameter_value_ids.clear();
    p
}
#[test]
fn phi_real_predecessor_loop_bound_and_global_closure() {
    for limit in [2, 3] {
        let p = count3();
        assert_eq!(
            p.retreating_edges(),
            ["j1".to_owned()].into_iter().collect()
        );
        let r = analyze(
            &p,
            &Budget {
                loop_unroll: limit,
                ..Default::default()
            },
            &mut ske_solver::Z3Solver::new(),
            |_, _| Ok(vec![]),
            &|| false,
            &mut |_| {},
        )
        .unwrap();
        assert_eq!(r.outcomes["enter"].status, Classification::Possible);
        if limit == 3 {
            assert!(r.exploration_closed);
            assert_eq!(r.cut_count, 0);
            assert_eq!(r.outcomes["exit"].status, Classification::Possible);
        } else {
            assert!(!r.exploration_closed);
            assert_eq!(r.cut_count, 1);
            assert_eq!(r.outcomes["exit"].explanation, "EXPLORATION_NOT_CLOSED");
        }
    }
}
